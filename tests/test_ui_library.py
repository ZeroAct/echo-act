    # ...and it counts down rather than repeating the policy figure.
    assert retention_text(summary, expires_at=result.expires_at, now=NOW + 1_800) == (
        "One-off · expires in about 30 min"
    )
    assert retention_text(summary, expires_at=result.expires_at, now=NOW + 7_200) == (
        "One-off · the audio has expired"
    )


