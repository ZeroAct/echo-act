def _job(
    store: Store,
    job_id: str,
    *,
    state: JobState = JobState.COMPLETE,
    retention: RetentionMode = RetentionMode.RETAINED,
    text: str | None = KOREAN,
    model_id: str = "supertonic-3",
    voice: str = "F1",
    created_at: float = NOW - 60,
    path: RequestPath = RequestPath.GUI,
) -> Job:
    """A history entry already in a terminal state, the way the library
    meets one: the engine is not involved in any of these tests."""
    job = Job(
        job_id=job_id,
        kind=JobKind.SPEECH,
        request_path=path,
        owner_client_id="cli_owner",
        state=JobState.ACCEPTED,
        source_text=text or "",
        settings=_settings(model_id, voice),
        budget=Budget(cpu_percent=20, memory_bytes=2 << 30, intra_op_threads=2),
        retention=retention,
        created_at=created_at,
    )
    store.create_job(job, at=created_at)
    if state is not JobState.ACCEPTED:
        if state in (JobState.COMPLETE, JobState.CANCELED):
            store.update_job_state(job_id, JobState.GENERATING, at=created_at + 1)
        if state is JobState.CANCELED:
            store.update_job_state(job_id, JobState.CANCELING, at=created_at + 2)
        if state is JobState.FAILED:
            store.record_job_error(job_id, "GENERATION_FAILED", at=created_at + 3)
        else:
            store.update_job_state(job_id, state, at=created_at + 3)
    if text is None:
        store.clear_job_source_text(job_id)
    return job


def _attach(
    store: Store,
    job_id: str,
    *,
    exists: bool = True,
    truncated: bool = False,
    expires_at: float | None = None,
    frames: int = 44_100,
) -> Result:
    payload = b"RIFF" + b"\0" * 2044
    relative = f"{job_id}.wav"
    if exists:
        target = store.audio_root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(payload[:64] if truncated else payload)
    return store.attach_result(
        Result(
            result_id="",
            job_id=job_id,
            sample_rate=44_100,
            channels=1,
            sample_width_bits=16,
            frame_count=frames,
            byte_size=len(payload),
            digest=hashlib.sha256(payload).hexdigest(),
            created_at=NOW - 30,
            expires_at=expires_at,
            relative_path=relative,
        ),
        at=NOW - 30,
    )


def _summary(store: Store, job_id: str):
    for item in store.list_jobs(limit=LIST_PAGE_MAX).items:
        if item.job_id == job_id:
            return item
    raise AssertionError(f"no summary for {job_id}")


