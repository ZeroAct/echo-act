def _spills(row: QWidget) -> list[str]:
    """Controls whose right edge falls outside the row that holds them."""
    return [
        child.accessibleName() or type(child).__name__
        for child in row.findChildren(QWidget)
        if child.parentWidget() is row and child.geometry().right() > row.width()
    ]


@pytest.mark.parametrize(
    ("width", "height", "scaling"),
    [(1280, 720, "100%"), (640, 360, "200%"), (560, 620, "half a screen")],
)
def test_the_screen_fits_the_narrowest_window_it_has_to(
    app, store, clock, width, height, scaling
) -> None:
    """N-30 sideways, not only downwards.

    1280x720 at 200% OS scaling is 640x360 logical pixels -- emulated by
    halving the size, the way ``test_ui_settings`` does -- and 560 is the
    width a content pane gets beside the rest of the window.  Nothing here
    scrolls horizontally, so a row of controls that cannot wrap would set a
    minimum width the window has to obey and the screen would be clipped
    with no way to reach what is off the edge.
    """
    store.save_document("Notes", KOREAN, at=NOW)
