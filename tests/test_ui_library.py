def test_listing_history_reads_no_audio_file(app, store, clock, monkeypatch) -> None:
    """F-40: a list is displayed without reading whole audio files.

    The shallow integrity check the detail panel runs is a ``stat``; opening
    the file is what this forbids, and it is what a digest would need.
    """
    opened: list[str] = []
    real_open = Path.open

    def spy(self, *args, **kwargs):
        if self.suffix == ".wav":
            opened.append(str(self))
        return real_open(self, *args, **kwargs)

    for i in range(5):
        _job(store, f"job_{i}", created_at=NOW - i)
        _attach(store, f"job_{i}")
    monkeypatch.setattr(Path, "open", spy)
    pane = _history(store, clock)
    assert pane.tree.topLevelItemCount() == 5
    assert opened == []


def test_listing_history_loads_only_the_snapshot_of_the_entry_it_opens(
    app, store, clock, monkeypatch
) -> None:
    """F-56 makes the body-text-free summary the default; the snapshot is a
    request of its own, so a page of twenty rows is not twenty of them."""
    asked: list[str] = []
    original = store.get_job_text

    def spy(job_id: str) -> str | None:
        asked.append(job_id)
        return original(job_id)

    for i in range(10):
        _job(store, f"job_{i}", created_at=NOW - i)
    monkeypatch.setattr(store, "get_job_text", spy)
    pane = _history(store, clock)
    assert pane.tree.topLevelItemCount() == 10
    assert asked == ["job_0"]  # the row selection opened, and nothing else


